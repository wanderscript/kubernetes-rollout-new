package main

import (
	"context"
	"encoding/json"
	"fmt"
	"log"
	"net/http"
	"os"
	"os/signal"
	"strconv"
	"strings"
	"sync/atomic"
	"syscall"
	"time"
)

type appState struct {
	ready       atomic.Bool
	failLiveness atomic.Bool
	requests    atomic.Uint64
	errors      atomic.Uint64
	durationNS  atomic.Uint64
}

type response struct {
	Version  string `json:"version"`
	Instance string `json:"instance"`
	Status   string `json:"status"`
}

func main() {
	version := env("APP_VERSION", "dev")
	instance := env("POD_NAME", "local")
	adminToken := env("LAB_ADMIN_TOKEN", "")
	addr := env("LISTEN_ADDR", ":8080")

	state := &appState{}
	state.ready.Store(true)

	mux := http.NewServeMux()

	mux.HandleFunc("GET /", func(w http.ResponseWriter, r *http.Request) {
		writeJSON(w, http.StatusOK, response{
			Version: version, Instance: instance, Status: "ok",
		})
	})

	mux.HandleFunc("GET /health/live", func(w http.ResponseWriter, r *http.Request) {
		if state.failLiveness.Load() {
			http.Error(w, "liveness intentionally failing", http.StatusServiceUnavailable)
			return
		}
		w.WriteHeader(http.StatusOK)
		_, _ = w.Write([]byte("ok\n"))
	})

	mux.HandleFunc("GET /health/ready", func(w http.ResponseWriter, r *http.Request) {
		if !state.ready.Load() {
			http.Error(w, "not ready", http.StatusServiceUnavailable)
			return
		}
		w.WriteHeader(http.StatusOK)
		_, _ = w.Write([]byte("ready\n"))
	})

	// Lab-only controls. Require a token and keep the Service internal.
	mux.HandleFunc("POST /admin/ready", func(w http.ResponseWriter, r *http.Request) {
		if !authorized(w, r, adminToken) {
			return
		}
		value, err := strconv.ParseBool(r.URL.Query().Get("value"))
		if err != nil {
			http.Error(w, "use ?value=true or ?value=false", http.StatusBadRequest)
			return
		}
		state.ready.Store(value)
		writeJSON(w, http.StatusOK, map[string]any{"ready": value})
	})

	mux.HandleFunc("POST /admin/liveness", func(w http.ResponseWriter, r *http.Request) {
		if !authorized(w, r, adminToken) {
			return
		}
		value, err := strconv.ParseBool(r.URL.Query().Get("fail"))
		if err != nil {
			http.Error(w, "use ?fail=true or ?fail=false", http.StatusBadRequest)
			return
		}
		state.failLiveness.Store(value)
		writeJSON(w, http.StatusOK, map[string]any{"liveness_failing": value})
	})

	mux.HandleFunc("GET /metrics", func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Content-Type", "text/plain; version=0.0.4; charset=utf-8")
		fmt.Fprintf(w, "# HELP rollout_http_requests_total Total HTTP requests handled by the application.\n")
		fmt.Fprintf(w, "# TYPE rollout_http_requests_total counter\nrollout_http_requests_total %d\n", state.requests.Load())
		fmt.Fprintf(w, "# HELP rollout_http_errors_total Total HTTP 5xx responses generated by the application.\n")
		fmt.Fprintf(w, "# TYPE rollout_http_errors_total counter\nrollout_http_errors_total %d\n", state.errors.Load())
		fmt.Fprintf(w, "# HELP rollout_http_request_duration_seconds_sum Sum of request handler durations in seconds.\n")
		fmt.Fprintf(w, "# TYPE rollout_http_request_duration_seconds_sum counter\nrollout_http_request_duration_seconds_sum %.9f\n", float64(state.durationNS.Load())/1e9)
	})

	handler := http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		start := time.Now()
		rec := &statusRecorder{ResponseWriter: w, status: http.StatusOK}
		mux.ServeHTTP(rec, r)
		state.requests.Add(1)
		state.durationNS.Add(uint64(time.Since(start).Nanoseconds()))
		if rec.status >= 500 {
			state.errors.Add(1)
		}
	})

	server := &http.Server{
		Addr:              addr,
		Handler:           handler,
		ReadHeaderTimeout: 5 * time.Second,
		IdleTimeout:       60 * time.Second,
	}

	sigCtx, stop := signal.NotifyContext(context.Background(), syscall.SIGTERM, syscall.SIGINT)
	defer stop()

	go func() {
		<-sigCtx.Done()
		log.Printf("shutdown signal received; marking unready")
		state.ready.Store(false)
		ctx, cancel := context.WithTimeout(context.Background(), 20*time.Second)
		defer cancel()
		if err := server.Shutdown(ctx); err != nil {
			log.Printf("graceful shutdown failed: %v", err)
			_ = server.Close()
		}
	}()

	log.Printf("starting version=%s instance=%s addr=%s", version, instance, addr)
	if err := server.ListenAndServe(); err != nil && err != http.ErrServerClosed {
		log.Fatal(err)
	}
	log.Printf("server stopped")
}

type statusRecorder struct {
	http.ResponseWriter
	status int
}

func (r *statusRecorder) WriteHeader(code int) {
	r.status = code
	r.ResponseWriter.WriteHeader(code)
}

func authorized(w http.ResponseWriter, r *http.Request, expected string) bool {
	if expected == "" || r.Header.Get("X-Lab-Token") != expected {
		http.Error(w, "forbidden", http.StatusForbidden)
		return false
	}
	return true
}

func writeJSON(w http.ResponseWriter, code int, value any) {
	w.Header().Set("Content-Type", "application/json")
	w.WriteHeader(code)
	_ = json.NewEncoder(w).Encode(value)
}

func env(key, fallback string) string {
	value := strings.TrimSpace(os.Getenv(key))
	if value == "" {
		return fallback
	}
	return value
}
